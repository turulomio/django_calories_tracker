"""
Recipe Import and Automatic Elaboration Management Module.

This module provides the management command `import_recipe` and underlying services
to scrape, analyze, summarize, and persist recipes from diverse sources (Web URLs,
YouTube videos, and local documents) into the database, generating structured `Recipes`,
`RecipesLinks`, associated `Files`, category associations, and automatic `Elaborations`
with ingredient mentions and preparation instructions using a local Ollama LLM instance.

========================================================================================
KEY FUNCTIONALITIES & ARCHITECTURE:
========================================================================================

1. Multi-Source Recipe Ingestion:
   - Web URLs (`--url`): Scrapes web pages, extracts semantic recipe text, titles,
     and meta descriptions while filtering out scripts, navigation, and boilerplate.
   - YouTube URLs:
     * Downloads highest-resolution video snapshot/thumbnail and saves it to `Files`,
       linking it as the Recipe's 'Main Photo' (`RecipesLinks`).
     * Extracts spoken subtitles and auto-generated captions (WebVTT) via `yt-dlp`.
     * Extracts and converts audio track to MP3 via `yt-dlp` for multimodal LLM processing.
     * Extracts video title, description, and metadata.
   - Local Documents (`--document` / `--file`): Extracts text from plain text, Markdown,
     HTML, JSON, and PDF files, attaching the original file to `Files` and `RecipesLinks`.
   - Existing Recipe Elaboration (`--from-recipe-id`): Generates an automatic elaboration
     for an already persisted `Recipes` record using all its linked sources.

2. Local LLM (Ollama) Integration & Resilient Parsing:
   - Integrates with local Ollama instances (`OllamaClient`, default model `gemma4:e2b`).
   - Supports multimodal audio and text prompts for precise culinary extraction.
   - Resilient Multi-Layer JSON Parser:
     * Supports `strict=False` parsing for unescaped control chars and newlines in strings.
     * Automatically cleans trailing commas in arrays and objects (`[...,]`, `{...,}`).
     * Auto-repairs unescaped backslashes and quotes.
     * Automatically balances and completes truncated JSON strings and containers.
     * Fallback regex parser to salvage structured recipe attributes if JSON decoding fails.
   - Internationalization (`--locale`, default `'es'`):
     * Dynamically prompts Ollama in the requested language (Spanish, English, etc.).
     * Localizes AI notices (e.g. `(Generado por IA)` / `(Generated by AI)`).

3. Database Persistence & Transactional Atomicity:
   - Full transactional safety (`@transaction.atomic`): All operations (Recipe creation,
     file uploads, link creations, category links, elaborations, ingredients, and text)
     are performed within atomic database transactions with complete rollback on error.
   - Strict Category Association: Associates recipes only with existing `RecipesCategories`
     found in the database, preventing the creation of unverified or orphan categories.
   - Elaborations & Rich Ingredient Spans: Enriches preparation steps (`ElaborationsTexts`)
     with HTML ingredient mention spans (`ElaborationsTexts.span_ingredient`).

4. High-Confidence Heuristic Product Matching (`ProductMatcher`):
   - Strict User Isolation: Matches ingredients ONLY against active, non-obsolete products
     owned by the target user (`Products.user == target_user`).
   - Normalization & Diacritic Stripping: Lowercases and strips accents/diacritics,
     punctuation, and redundant whitespace.
   - Morphological Normalization: Singularization and stemming (e.g. 'Huevos' -> 'Huevo').
   - Stopwords Filtering: Strips culinary filler words ('de', 'fresco', 'picado', 'crudo', etc.).
   - Conflicting Modifier Protection: Rejects matches containing mutually exclusive modifiers
     (e.g., olive oil vs sunflower oil, white wine vs red wine, whole milk vs skim milk).
   - High Confidence Threshold (>= 85%): Eliminates loose substring false positives
     (e.g., 'Sal' vs 'Salmón', 'Ajo' vs 'Majo').
   - Omission of Unmatched Items: Never inserts blank or placeholder product records.

5. CLI Options & Management Command:
   - `--url <URL>`: Scrapes and imports recipe from web page or YouTube video.
   - `--document <PATH>` / `--file <PATH>`: Imports recipe from a local document.
   - `--locale <CODE>`: Locale/language code (default: 'es').
   - `--user_id <ID>`: ID of the user who will own the recipe and whose products are matched.
   - `--username <NAME>`: Username of the user who will own the recipe.
   - `--from-recipe-id <ID>`: Generates automatic elaboration for an existing recipe ID.
   - `--no-elaboration`: Imports Recipe, Links, Categories, and Files without creating Elaborations.
"""

