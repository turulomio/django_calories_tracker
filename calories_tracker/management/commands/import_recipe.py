class OllamaClient:
    """
    Client for interacting with local Ollama API.
    """

    def __init__(self, base_url: str = None, model: str = None):
        """
        Initialize the Ollama client with base URL and model name.

        :param base_url: Ollama server URL (defaults to settings.OLLAMA_BASE_URL)
        :param model: Model identifier (defaults to settings.OLLAMA_MODEL)
        """
        self.base_url = (base_url or getattr(settings, "OLLAMA_BASE_URL", "http://localhost:11434")).rstrip("/")
        self.model = model or getattr(settings, "OLLAMA_MODEL", "gemma4:e2b")

    def generate(
        self,
        prompt: str,
        system_prompt: str = None,
        format_json: bool = True,
        audio_base64: str = None,
    ) -> dict | str:
        """
        Send a generation request to the Ollama server.

        :param prompt: User prompt to send to the model.
        :param system_prompt: Optional system prompt to guide LLM behavior.
        :param format_json: If True, request JSON response format from Ollama.
        :param audio_base64: Optional base64 encoded audio track to send to Ollama.
        :return: Parsed JSON dict if format_json is True, otherwise response string.
        :raises RuntimeError: On network error or Ollama execution failure.
        """
        endpoint = f"{self.base_url}/api/generate"
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": 0.1,
                "num_predict": 4096,
            },
        }
        if system_prompt:
            payload["system"] = system_prompt
        if format_json:
            payload["format"] = "json"
        if audio_base64:
            payload["audio"] = [audio_base64]
            payload["images"] = [audio_base64]

        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            endpoint,
            data=data,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=180) as response:
                res_body = response.read().decode("utf-8")
                res_json = json.loads(res_body)
                raw_response = res_json.get("response", "")
        except urllib.error.URLError as e:
            raise RuntimeError(
                f"Error connecting to Ollama at {endpoint}. Ensure Ollama is running and model '{self.model}' is available. Error: {e}"
            ) from e
        except Exception as e:
            raise RuntimeError(f"Unexpected error communicating with Ollama: {e}") from e

        if format_json:
            return self._parse_json_response(raw_response)
        return raw_response

    @classmethod
    def _parse_json_response(cls, raw_text: str) -> dict:
        """
        Clean, repair, and parse a JSON response from the LLM, handling markdown codeblocks,
        unescaped newlines, trailing commas, missing delimiters, and truncated responses.

        :param raw_text: Raw string returned by LLM.
        :return: Parsed dictionary.
        """
        if not raw_text or not raw_text.strip():
            raise ValueError("Empty response received from LLM.")

        cleaned = raw_text.strip()

        # 1. Remove markdown fences if present
        match_codeblock = re.search(r"```(?:json)?\s*(.*?)\s*```", cleaned, re.DOTALL | re.IGNORECASE)
        if match_codeblock:
            cleaned = match_codeblock.group(1).strip()
        else:
            cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
            cleaned = re.sub(r"\s*```$", "", cleaned)
            cleaned = cleaned.strip()

        # 2. Extract substring between first '{' and last '}'
        first_brace = cleaned.find("{")
        last_brace = cleaned.rfind("}")
        if first_brace != -1 and last_brace != -1 and last_brace >= first_brace:
            json_candidate = cleaned[first_brace : last_brace + 1]
        else:
            json_candidate = cleaned

        # Attempt A: Direct loads with strict=False (allows unescaped control chars / literal newlines in strings)
        try:
            return json.loads(json_candidate, strict=False)
        except Exception:
            pass

        # Attempt B: Strip trailing commas before closing braces/brackets
        no_trailing = re.sub(r",\s*([\]}])", r"\1", json_candidate)
        try:
            return json.loads(no_trailing, strict=False)
        except Exception:
            pass

        # Attempt C: Clean and sanitize escape sequences
        repaired = cls._repair_json_string(no_trailing)
        try:
            return json.loads(repaired, strict=False)
        except Exception:
            pass

        # Attempt D: Auto-close incomplete/truncated JSON structures
        auto_closed = cls._auto_close_json(no_trailing)
        try:
            return json.loads(auto_closed, strict=False)
        except Exception:
            pass

        # Attempt E: Regex-based fallback extraction of recipe attributes
        fallback_data = cls._extract_fallback_recipe_data(raw_text)
        if fallback_data.get("name") and fallback_data.get("name") != "Receta sin título":
            logger.warning("Recovered structured recipe data via regex fallback parser.")
            return fallback_data

        # Final attempt: try parsing original cleaned with strict=False or return fallback
        try:
            return json.loads(cleaned, strict=False)
        except Exception as err:
            if fallback_data and fallback_data.get("name"):
                return fallback_data
            raise ValueError(f"Could not parse or repair JSON from LLM output: {err}. Raw output:\n{raw_text}") from err

    @staticmethod
    def _repair_json_string(text: str) -> str:
        """
        Repair common JSON formatting defects generated by LLMs.

        :param text: Candidate JSON string.
        :return: Sanitized string.
        """
        text = re.sub(r",\s*([\]}])", r"\1", text)
        text = re.sub(r'\\(?!["\\/bfnrtu])', r'\\\\', text)
        return text

    @staticmethod
    def _auto_close_json(text: str) -> str:
        """
        Attempt to complete a truncated JSON string by closing open strings, lists, and objects.

        :param text: Incomplete JSON candidate.
        :return: Completed JSON string.
        """
        text = text.strip()
        first_brace = text.find("{")
        if first_brace == -1:
            return text
        text = text[first_brace:]

        in_string = False
        escape = False
        stack = []

        for char in text:
            if escape:
                escape = False
                continue
            if char == "\\":
                escape = True
                continue
            if char == '"':
                in_string = not in_string
                continue
            if not in_string:
                if char in "{[":
                    stack.append(char)
                elif char == "}":
                    if stack and stack[-1] == "{":
                        stack.pop()
                elif char == "]":
                    if stack and stack[-1] == "[":
                        stack.pop()

        if in_string:
            text += '"'

        text = re.sub(r'[,:\s]+$', '', text)

        while stack:
            opener = stack.pop()
            if opener == "{":
                text += "}"
            elif opener == "[":
                text += "]"

        text = re.sub(r",\s*([\]}])", r"\1", text)
        return text

    @staticmethod
    def _extract_fallback_recipe_data(text: str) -> dict:
        """
        Extract recipe fields using regex when JSON parser cannot repair the string.

        :param text: Raw response text from LLM.
        :return: Dict with extracted recipe keys.
        """
        data = {
            "name": "Receta importada",
            "comment": "",
            "food_type": "Homemade food",
            "categories": [],
            "diners": 4,
            "ingredients": [],
            "steps": "",
        }

        # Name
        m_name = re.search(r'"name"\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        if m_name:
            data["name"] = m_name.group(1).replace(r'\"', '"').strip()

        # Comment
        m_comm = re.search(r'"comment"\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        if m_comm:
            data["comment"] = m_comm.group(1).replace(r'\"', '"').strip()

        # Food Type
        m_ft = re.search(r'"food_type"\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        if m_ft:
            data["food_type"] = m_ft.group(1).replace(r'\"', '"').strip()

        # Diners
        m_din = re.search(r'"diners"\s*:\s*(\d+)', text)
        if m_din:
            try:
                data["diners"] = int(m_din.group(1))
            except ValueError:
                data["diners"] = 4

        # Steps
        m_steps = re.search(r'"steps"\s*:\s*"((?:[^"\\]|\\.)*)"', text, re.DOTALL)
        if m_steps:
            data["steps"] = m_steps.group(1).replace(r"\n", "\n").replace(r'\"', '"')
        else:
            m_steps_block = re.search(r'"steps"\s*:\s*([^,}]+)', text)
            if m_steps_block:
                data["steps"] = m_steps_block.group(1).strip().strip('"')

        # Categories
        m_cats = re.search(r'"categories"\s*:\s*\[(.*?)\]', text, re.DOTALL)
        if m_cats:
            cat_items = re.findall(r'"([^"]+)"', m_cats.group(1))
            data["categories"] = [c.strip() for c in cat_items if c.strip()]

        # Ingredients (match objects inside array)
        m_ings = re.search(r'"ingredients"\s*:\s*\[(.*?)\]\s*(?:,|\})', text, re.DOTALL)
        if m_ings:
            ing_blocks = re.findall(r'\{([^{}]+)\}', m_ings.group(1))
            for block in ing_blocks:
                ing_obj = {}
                name_m = re.search(r'"name"\s*:\s*"((?:[^"\\]|\\.)*)"', block)
                if name_m:
                    ing_obj["name"] = name_m.group(1).replace(r'\"', '"').strip()
                amt_m = re.search(r'"amount"\s*:\s*([0-9.]+)', block)
                if amt_m:
                    try:
                        ing_obj["amount"] = float(amt_m.group(1))
                    except ValueError:
                        ing_obj["amount"] = 100
                unit_m = re.search(r'"unit"\s*:\s*"((?:[^"\\]|\\.)*)"', block)
                if unit_m:
                    ing_obj["unit"] = unit_m.group(1).strip()
                comm_m = re.search(r'"comment"\s*:\s*"((?:[^"\\]|\\.)*)"', block)
                if comm_m:
                    ing_obj["comment"] = comm_m.group(1).replace(r'\"', '"').strip()
                if ing_obj.get("name"):
                    data["ingredients"].append(ing_obj)

        return data


class YouTubeHelper:
    """
    Helper for detecting YouTube URLs and fetching video thumbnail images.
    """

    YOUTUBE_REGEX = re.compile(
        r"(?:https?:\/\/)?(?:www\.|m\.)?(?:youtube\.com\/(?:watch\?v=|embed\/|v\/|shorts\/)|youtu\.be\/)([a-zA-Z0-9_-]{11})"
    )

    @classmethod
    def get_video_id(cls, url: str) -> str | None:
        """
        Extract the 11-character YouTube video ID from a URL if present.

        :param url: URL string to inspect.
        :return: Video ID string or None.
        """
        if not url:
            return None
        match = cls.YOUTUBE_REGEX.search(url)
        return match.group(1) if match else None

    @classmethod
    def fetch_thumbnail(cls, video_id: str) -> tuple[bytes, str] | None:
        """
        Download the highest available resolution thumbnail image for a YouTube video.

        :param video_id: 11-character YouTube video ID.
        :return: Tuple (image_bytes, mime_type) or None if download fails.
        """
        print(f"[YouTube] Descargando snapshot/miniatura para el vídeo '{video_id}'...", flush=True)
        thumbnail_urls = [
            f"https://img.youtube.com/vi/{video_id}/maxresdefault.jpg",
            f"https://img.youtube.com/vi/{video_id}/hqdefault.jpg",
            f"https://img.youtube.com/vi/{video_id}/0.jpg",
        ]
        headers = {
            "User-Agent": (
                "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
            )
        }
        for thumb_url in thumbnail_urls:
            try:
                req = urllib.request.Request(thumb_url, headers=headers)
                with urllib.request.urlopen(req, timeout=15) as resp:
                    if resp.status == 200:
                        content = resp.read()
                        # Some missing maxresdefault return 1097 byte placeholder; check valid length
                        if len(content) > 1500:
                            print(f"[YouTube] ✓ Snapshot descargado exitosamente ({len(content)} bytes, image/jpeg)", flush=True)
                            return content, "image/jpeg"
            except Exception as e:
                logger.debug("Failed downloading thumbnail from %s: %s", thumb_url, e)
        print(f"[YouTube] ⚠ No se pudo obtener snapshot/miniatura para '{video_id}'", flush=True)
        return None

    @classmethod
    def clean_vtt(cls, vtt_content: str) -> str:
        """
        Strip timing tags and formatting from WebVTT subtitles to get clean plain text.

        :param vtt_content: Raw VTT subtitle content.
        :return: Cleaned subtitle text.
        """
        lines = []
        for line in vtt_content.splitlines():
            line = line.strip()
            if (
                not line
                or line.startswith("WEBVTT")
                or line.startswith("Kind:")
                or line.startswith("Language:")
                or line.startswith("Style:")
                or line.startswith("NOTE")
                or line.startswith("REGION")
                or "-->" in line
                or line.isdigit()
            ):
                continue
            cleaned = re.sub(r"<[^>]+>", "", line).strip()
            if cleaned and (not lines or lines[-1] != cleaned):
                lines.append(cleaned)
        return " ".join(lines)

    @classmethod
    def extract_full_youtube_data(cls, url: str, video_id: str, locale: str = "es") -> dict:
        """
        Extract title, description, spoken subtitles/transcript, and audio track from YouTube using yt-dlp.

        :param url: YouTube video URL.
        :param video_id: 11-character YouTube video ID.
        :param locale: Preferred language code for subtitle extraction (default: "es").
        :return: Dict containing title, description, transcript, combined_text, and base64 audio.
        """
        result = {
            "title": "",
            "description": "",
            "transcript": "",
            "combined_text": "",
            "audio_base64": None,
        }

        ytdlp_bin = shutil.which("yt-dlp")
        tmp_dir = getattr(settings, "TMPDIR", "/tmp")

        if ytdlp_bin:
            # 1. Extract metadata and subtitles/transcripts
            print(f"[YouTube] Extrayendo metadatos y subtítulos con yt-dlp (ID: {video_id})...", flush=True)
            sub_template = f"{tmp_dir}/yt_sub_{video_id}"
            try:
                for f in glob(f"{sub_template}*"):
                    try:
                        os.remove(f)
                    except OSError:
                        pass

                clean_loc = (locale or "es").split("_")[0].lower()
                sub_langs = f"{clean_loc},{clean_loc}-orig,es,en,es-orig,en-orig,es-419"

                proc = subprocess.run(
                    [
                        ytdlp_bin,
                        "--dump-json",
                        "--skip-download",
                        "--write-auto-sub",
                        "--write-sub",
                        "--sub-lang", sub_langs,
                        "--sub-format", "vtt/best",
                        "-o", f"subtitle:{sub_template}",
                        url,
                    ],
                    capture_output=True,
                    text=True,
                    timeout=45,
                )
                if proc.returncode == 0 and proc.stdout:
                    try:
                        meta = json.loads(proc.stdout)
                        result["title"] = meta.get("title", "")
                        result["description"] = meta.get("description", "")
                        print(f"[YouTube] ✓ Título: '{result['title']}'", flush=True)
                    except Exception as e:
                        logger.debug("Failed parsing yt-dlp metadata JSON: %s", e)

                # Check for extracted subtitle files
                sub_files = glob(f"{sub_template}*.vtt")
                if sub_files:
                    try:
                        with open(sub_files[0], "r", encoding="utf-8", errors="replace") as sf:
                            result["transcript"] = cls.clean_vtt(sf.read())
                        print(f"[YouTube] ✓ Subtítulos extraídos ({len(result['transcript'])} caracteres)", flush=True)
                    except Exception as e:
                        logger.debug("Failed reading subtitle file: %s", e)
                    finally:
                        for f in sub_files:
                            try:
                                os.remove(f)
                            except OSError:
                                pass
                else:
                    print("[YouTube] ℹ No se encontraron subtítulos VTT; se usará la descripción", flush=True)
            except Exception as e:
                logger.debug("yt-dlp metadata/subtitle extraction error: %s", e)
                print(f"[YouTube] ⚠ Error extrayendo subtítulos: {e}", flush=True)

            # 2. Extract audio track from video
            print(f"[YouTube] Extrayendo y convirtiendo pista de audio a MP3 con yt-dlp (ID: {video_id})...", flush=True)
            audio_template = f"{tmp_dir}/yt_audio_{video_id}.%(ext)s"
            try:
                for f in glob(f"{tmp_dir}/yt_audio_{video_id}.*"):
                    try:
                        os.remove(f)
                    except OSError:
                        pass

                audio_proc = subprocess.run(
                    [
                        ytdlp_bin,
                        "-x",
                        "--audio-format", "mp3",
                        "--audio-quality", "5",
                        "-o", audio_template,
                        url,
                    ],
                    capture_output=True,
                    timeout=90,
                )
                if audio_proc.returncode == 0:
                    generated_audios = glob(f"{tmp_dir}/yt_audio_{video_id}.*")
                    if generated_audios:
                        with open(generated_audios[0], "rb") as af:
                            audio_bytes = af.read()
                            if audio_bytes:
                                result["audio_base64"] = base64.b64encode(audio_bytes).decode("utf-8")
                                print(f"[YouTube] ✓ Pista de audio convertida y codificada en Base64 ({len(audio_bytes)} bytes)", flush=True)
                        for af_path in generated_audios:
                            try:
                                os.remove(af_path)
                            except OSError:
                                pass
                else:
                    print(f"[YouTube] ⚠ Falló la conversión de audio: {audio_proc.stderr}", flush=True)
            except Exception as e:
                logger.debug("yt-dlp audio extraction error: %s", e)
                print(f"[YouTube] ⚠ Error al extraer pista de audio: {e}", flush=True)

        # Fallback to HTML extraction if title or description are empty
        if not result["title"] or not result["description"]:
            try:
                print("[YouTube] Realizando extracción fallback HTML...", flush=True)
                html_text, html_title = RecipeTextExtractor.extract_from_url(url)
                if not result["title"]:
                    result["title"] = html_title
                if not result["description"]:
                    result["description"] = html_text
            except Exception as e:
                logger.debug("HTML fallback error: %s", e)

        # Combine all gathered information into rich prompt context
        combined = f"Title: {result['title']}\n\nDescription:\n{result['description']}\n"
        if result["transcript"]:
            combined += f"\nVideo Transcript / Spoken Subtitles:\n{result['transcript']}\n"
        result["combined_text"] = combined.strip()

        return result


class RecipeTextExtractor:
    """
    Extracts raw text content from URLs and local documents.
    """

    @staticmethod
    def extract_from_url(url: str) -> tuple[str, str]:
        """
        Fetch HTML from URL and strip tags to get readable plain text.

        :param url: Web page URL to fetch.
        :return: Tuple of (extracted_text, title).
        :raises RuntimeError: If URL cannot be retrieved.
        """
        print(f"[Web] Extrayendo contenido de la URL: {url}...", flush=True)
        headers = {
            "User-Agent": (
                "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
                "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
            )
        }
        req = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=30) as response:
                charset = response.headers.get_content_charset() or "utf-8"
                html_bytes = response.read()
                html_text = html_bytes.decode(charset, errors="replace")
        except Exception as e:
            raise RuntimeError(f"Failed to fetch content from URL '{url}': {e}") from e

        # Extract title
        title_match = re.search(r"<title[^>]*>(.*?)</title>", html_text, re.IGNORECASE | re.DOTALL)
        title = title_match.group(1).strip() if title_match else ""

        # Extract meta description / og:description
        meta_desc = ""
        meta_desc_match = re.search(
            r'<meta\s+(?:name|property)=["\'](?:description|og:description)["\']\s+content=["\'](.*?)["\']',
            html_text,
            re.IGNORECASE | re.DOTALL,
        )
        if not meta_desc_match:
            meta_desc_match = re.search(
                r'<meta\s+content=["\'](.*?)["\']\s+(?:name|property)=["\'](?:description|og:description)["\']',
                html_text,
                re.IGNORECASE | re.DOTALL,
            )
        if meta_desc_match:
            meta_desc = meta_desc_match.group(1).strip()

        # Remove scripts, styles, header, footer, nav
        cleaned = re.sub(r"<(script|style|nav|footer|header|aside)[^>]*>.*?</\1>", " ", html_text, flags=re.IGNORECASE | re.DOTALL)
        # Strip all HTML tags
        text = re.sub(r"<[^>]+>", " ", cleaned)
        # Unescape HTML entities
        text = html.unescape(text)
        meta_desc = html.unescape(meta_desc)
        title = html.unescape(title)

        if meta_desc:
            text = f"Title: {title}\nDescription: {meta_desc}\n\nContent:\n{text}"

        # Collapse whitespace
        text = re.sub(r"\s+", " ", text).strip()
        print(f"[Web] ✓ Texto extraído: '{title}' ({len(text)} caracteres)", flush=True)

        return text, title

    @staticmethod
    def extract_from_file(file_path: str) -> tuple[str, bytes, str]:
        """
        Read local document or file content and determine mime type.

        :param file_path: Path to the local file.
        :return: Tuple of (extracted_text, raw_bytes, mime_type).
        :raises FileNotFoundError: If file does not exist.
        :raises RuntimeError: If file cannot be read.
        """
        if not path.isfile(file_path):
            raise FileNotFoundError(f"File not found: {file_path}")

        mime_type, _encoding = mimetypes.guess_type(file_path)
        if not mime_type:
            mime_type = "application/octet-stream"

        print(f"[Documento] Leyendo archivo local '{file_path}' (MIME: {mime_type})...", flush=True)

        with open(file_path, "rb") as f:
            raw_bytes = f.read()

        text = ""
        # Handle plain text, markdown, html, json
        if mime_type.startswith("text/") or file_path.endswith((".md", ".txt", ".html", ".htm", ".json", ".rst")):
            try:
                text = raw_bytes.decode("utf-8")
            except UnicodeDecodeError:
                text = raw_bytes.decode("latin-1", errors="replace")
        elif file_path.lower().endswith(".pdf"):
            # Attempt to extract text from PDF if pypdf or PyPDF2 is installed
            try:
                import pypdf
                import io
                reader = pypdf.PdfReader(io.BytesIO(raw_bytes))
                text = "\n".join([page.extract_text() or "" for page in reader.pages])
            except ImportError:
                # Fallback basic string extraction for ASCII streams
                text = re.sub(r"[^\x20-\x7E\n\r\t]", " ", raw_bytes.decode("latin-1", errors="replace"))
        else:
            # Generic binary fallback string extraction
            text = raw_bytes.decode("utf-8", errors="replace")

        # Collapse whitespace
        text = re.sub(r"[ \t]+", " ", text).strip()
        print(f"[Documento] ✓ Texto extraído ({len(text)} caracteres, {len(raw_bytes)} bytes)", flush=True)
        return text, raw_bytes, mime_type


class ProductMatcher:
    """
    High-confidence heuristic matcher to safely map recipe ingredient names
    to existing user products without introducing false positive matches.
    """

    STOPWORDS = {
        "de", "del", "la", "el", "los", "las", "un", "una", "unos", "unas",
        "para", "con", "sin", "y", "e", "o", "u", "al", "en", "por",
        "fresco", "fresca", "frescos", "frescas", "natural", "naturales",
        "crudo", "cruda", "crudos", "crudas", "troceado", "troceada", "picado", "picada",
        "rallado", "rallada", "cocido", "cocida", "frito", "frita", "asado", "asada",
        "fresh", "raw", "chopped", "diced", "sliced", "grated", "cooked", "fried",
    }

    # Groups of mutually exclusive modifier tokens. If ingredient and product specify different
    # tokens from the same group, they MUST NOT match.
    MUTUALLY_EXCLUSIVE_MODIFIER_GROUPS = [
        {"oliva", "girasol", "coco", "sesamo", "maiz", "soja", "palma", "colza", "cacahuete", "aguacate"},
        {"entera", "desnatada", "semidesnatada", "skim", "whole", "semi", "descremada"},
        {"blanco", "tinto", "rosado", "negro", "verde", "rojo", "amarillo", "morado", "white", "red", "black", "green", "yellow"},
        {"vaca", "cabra", "oveja", "soja", "avena", "almendra", "arroz", "coco", "avellana"},
        {"trigo", "centeno", "espelta", "maiz", "maicena", "arroz", "avena", "garbanzo"},
        {"dulce", "salado", "amargo", "picante", "agridulce", "sweet", "salty", "spicy"},
        {"pechuga", "muslo", "ala", "lomo", "solomillo", "costilla", "higado", "picada"},
        {"molido", "grano", "polvo", "entero", "hoja", "rama"},
    ]

    CONFIDENCE_THRESHOLD = 0.85

    @classmethod
    def normalize_text(cls, text: str) -> str:
        """
        Normalize text by lowercasing, removing accents, punctuation, and extra whitespace.

        :param text: Input string.
        :return: Normalized string.
        """
        if not text:
            return ""
        text = text.lower().strip()
        nfkd = unicodedata.normalize("NFKD", text)
        no_accents = "".join(c for c in nfkd if not unicodedata.combining(c))
        cleaned = re.sub(r"[^\w\s]", " ", no_accents)
        return re.sub(r"\s+", " ", cleaned).strip()

    @classmethod
    def singularize_word(cls, word: str) -> str:
        """
        Basic singularization for Spanish and English words.

        :param word: Word string.
        :return: Singularized word.
        """
        if len(word) <= 3:
            return word
        if word.endswith("ces"):
            return word[:-3] + "z"
        if word.endswith("es") and word[-3] not in "aeiou":
            return word[:-2]
        if word.endswith("s") and not word.endswith("ss"):
            return word[:-1]
        return word

    @classmethod
    def extract_meaningful_tokens(cls, text: str) -> tuple[list[str], set[str]]:
        """
        Extract normalized, singularized, non-stopword tokens from a text string.

        :param text: Input string.
        :return: Tuple of (ordered_tokens_list, tokens_set).
        """
        norm = cls.normalize_text(text)
        tokens = [cls.singularize_word(w) for w in norm.split() if w and w not in cls.STOPWORDS]
        return tokens, set(tokens)

    @classmethod
    def has_conflicting_modifiers(cls, ing_tokens_set: set[str], prod_tokens_set: set[str]) -> bool:
        """
        Check if ingredient and product contain mutually exclusive distinguishing tokens.

        :param ing_tokens_set: Set of meaningful tokens in ingredient.
        :param prod_tokens_set: Set of meaningful tokens in product.
        :return: True if conflicting modifiers exist, False otherwise.
        """
        for group in cls.MUTUALLY_EXCLUSIVE_MODIFIER_GROUPS:
            ing_intersect = ing_tokens_set.intersection(group)
            prod_intersect = prod_tokens_set.intersection(group)
            if ing_intersect and prod_intersect and ing_intersect != prod_intersect:
                return True
        return False

    @classmethod
    def calculate_confidence(cls, ing_name: str, prod_name: str) -> float:
        """
        Calculate match confidence score between an ingredient name and a product name.

        :param ing_name: Ingredient name from recipe.
        :param prod_name: Product name from user database.
        :return: Float score between 0.0 and 1.0.
        """
        if not ing_name or not prod_name:
            return 0.0

        raw_ing = ing_name.strip().lower()
        raw_prod = prod_name.strip().lower()

        # 1. Exact raw match
        if raw_ing == raw_prod:
            return 1.0

        norm_ing = cls.normalize_text(ing_name)
        norm_prod = cls.normalize_text(prod_name)

        # 2. Exact normalized match (ignoring accents, case, punctuation)
        if norm_ing == norm_prod:
            return 0.98

        ing_tokens, ing_set = cls.extract_meaningful_tokens(ing_name)
        prod_tokens, prod_set = cls.extract_meaningful_tokens(prod_name)

        if not ing_tokens or not prod_tokens:
            return 0.0

        # Check for conflicting modifiers (e.g. olive oil vs sunflower oil)
        if cls.has_conflicting_modifiers(ing_set, prod_set):
            return 0.0

        # 3. Exact token set match (ignoring word order and stopwords)
        if ing_set == prod_set:
            return 0.95

        stem_ing = " ".join(ing_tokens)
        stem_prod = " ".join(prod_tokens)

        # 4. Exact stemmed sequence match
        if stem_ing == stem_prod:
            return 0.94

        # 5. Sequence similarity over normalized and stemmed representations
        ratio_norm = difflib.SequenceMatcher(None, norm_ing, norm_prod).ratio()
        ratio_stem = difflib.SequenceMatcher(None, stem_ing, stem_prod).ratio()
        base_ratio = max(ratio_norm, ratio_stem)

        # Ensure that if the ingredient has key tokens, they are predominantly in the product
        if len(ing_set) == 1 and len(prod_set) == 1:
            single_ing = list(ing_set)[0]
            single_prod = list(prod_set)[0]
            if single_ing != single_prod:
                token_sim = difflib.SequenceMatcher(None, single_ing, single_prod).ratio()
                if token_sim < 0.88 or min(len(single_ing), len(single_prod)) <= 3:
                    return 0.0
                return token_sim * 0.9

        # If one token set is a subset of the other, check if all essential tokens are matched
        if ing_set.issubset(prod_set) or prod_set.issubset(ing_set):
            common_count = len(ing_set.intersection(prod_set))
            total_count = max(len(ing_set), len(prod_set))
            subset_ratio = common_count / total_count
            if subset_ratio >= 0.80:
                return max(base_ratio, subset_ratio * 0.92)

        return base_ratio

    @classmethod
    def find_best_product(cls, ing_name: str, candidate_products) -> tuple[models.Products | None, float]:
        """
        Find the single product with the highest confidence score exceeding CONFIDENCE_THRESHOLD.

        :param ing_name: Name of ingredient from recipe.
        :param candidate_products: Iterable / QuerySet of user Products.
        :return: Tuple (best_product, confidence_score) or (None, 0.0).
        """
        best_product = None
        best_score = 0.0

        for product in candidate_products:
            p_name = getattr(product, "name", "")
            if not p_name or not p_name.strip():
                continue

            score = cls.calculate_confidence(ing_name, p_name)
            if score > best_score:
                best_score = score
                best_product = product
                if score >= 0.98:  # Near perfect match, early exit
                    break

        if best_score >= cls.CONFIDENCE_THRESHOLD:
            return best_product, best_score
        return None, best_score


